// Generates crates/writr-acorn/src/generated/tables.rs from the pinned
// acorn@8.18.0 that remark-mdx parses expressions with, and the crate's
// LICENSES.txt for the packages it ports. The tables hold identifier
// start/part code point ranges (acorn's `isIdentifierStart/Char(cp, true)`)
// and the ECMAScript 2024 Unicode property names its RegExp validator
// accepts. The data variables are module-private, so the dist file is
// evaluated in an isolated context with its `export` statement removed.
//
// Run from the repo root: node writr-rs/tools/gen-acorn-tables.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { pinnedDir } from "./pinned.mjs";

const OUT = path.join(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
	"crates",
	"writr-acorn",
	"src",
	"generated",
	"tables.rs",
);

const source = fs.readFileSync(
	path.join(pinnedDir("acorn", "8.18.0"), "dist", "acorn.mjs"),
	"utf8",
);
const exportAt = source.lastIndexOf("\nexport {");
if (exportAt === -1) throw new Error("acorn.mjs export statement not found");
const acorn = vm.runInNewContext(
	`${source.slice(0, exportAt)}
;({
	isIdentifierStart,
	isIdentifierChar,
	binary: unicodeBinaryProperties[14],
	binaryOfStrings: unicodeBinaryPropertiesOfStrings[14],
	generalCategory: unicodeGeneralCategoryValues,
	script: unicodeScriptValues[14],
	version,
})`,
	{ console },
);
if (acorn.version !== "8.18.0") throw new Error(`acorn ${acorn.version}`);

function ranges(test) {
	const out = [];
	let start = -1;
	for (let cp = 0; cp <= 0x10ffff + 1; cp++) {
		const hit = cp <= 0x10ffff && test(cp);
		if (hit && start === -1) start = cp;
		if (!hit && start !== -1) {
			out.push([start, cp - 1]);
			start = -1;
		}
	}
	return out;
}

const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const rangeTable = (name, list) =>
	`pub static ${name}: &[(u32, u32)] = &[\n${list
		.map(([a, b]) => `\t(${hex(a)}, ${hex(b)}),`)
		.join("\n")}\n];`;
const words = (name, value) => {
	const list = value.split(" ").filter(Boolean);
	return `pub static ${name}: &[&str] = &[\n${list
		.map((word) => `\t${JSON.stringify(word)},`)
		.join("\n")}\n];`;
};

const body = `// @generated by writr-rs/tools/gen-acorn-tables.mjs — do not edit.
//
// Source: acorn@8.18.0 (dist/acorn.mjs). Inclusive code point ranges for
// \`isIdentifierStart(cp, true)\` / \`isIdentifierChar(cp, true)\`, sorted for
// binary search, plus the ecmaVersion >= 14 Unicode property name lists used
// by acorn's RegExp validator.

${rangeTable("ID_START", ranges((cp) => acorn.isIdentifierStart(cp, true)))}

${rangeTable("ID_CONTINUE", ranges((cp) => acorn.isIdentifierChar(cp, true)))}

${words("BINARY_PROPERTIES", `${acorn.binary} ${acorn.generalCategory}`)}

${words("BINARY_PROPERTIES_OF_STRINGS", acorn.binaryOfStrings)}

${words("GENERAL_CATEGORY_VALUES", acorn.generalCategory)}

${words("SCRIPT_VALUES", acorn.script)}
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);
console.log(`wrote ${path.relative(process.cwd(), OUT)}`);

// The ported packages, pinned to the versions remark-mdx resolves.
const ported = [
	["acorn", "8.18.0"],
	["acorn-jsx", "5.3.2"],
	["micromark-util-events-to-acorn", "2.0.3"],
];
const licenses = ported.map(([name, version]) => {
	const dir = pinnedDir(name, version);
	const file = fs
		.readdirSync(dir)
		.find((entry) => /^(license|copying)(\.|$)/i.test(entry));
	if (!file) throw new Error(`Missing license for ${name}`);
	return `## ${name}@${version}\n\n${fs.readFileSync(path.join(dir, file), "utf8").trim()}\n`;
});
const LICENSES = path.join(path.dirname(OUT), "..", "..", "LICENSES.txt");
fs.writeFileSync(
	LICENSES,
	`writr-acorn is a Rust port of the following packages.\n\n${licenses.join("\n")}`,
);
console.log(`wrote ${path.relative(process.cwd(), LICENSES)}`);
